"""
Video Processor Module
Handles video file ingestion, camera streaming, frame extraction,
procedural synthetic traffic stream simulation, and batch/sampled computer vision analytics.

Key Features:
1. Frame Sampling & Batch Processing: Configurable frame-sampling interval (e.g. process every k-th frame)
   and batch processing to manage CPU utilization on resource-constrained platforms.
2. Robust Video Validation: Graceful error handling for unsupported file formats, corrupted/truncated videos,
   missing codecs, and empty frames.
3. Multi-Object Tracking Integration: Associates detections with persistent track IDs, computing cumulative
   unique vehicles vs instantaneous occupancy vs traffic flow rate.
4. Procedural Synthetic Engine: High-fidelity 4-way intersection simulation with ground-truth vehicle tracks
   for zero-dependency testing and demonstration.
5. Independent Importability: Zero dependencies on Streamlit UI code.
"""

from dataclasses import dataclass, field
import os
import time
from typing import Generator, Tuple, List, Optional, Dict, Any, Set
import numpy as np
import cv2

from .vehicle_detector import Detection, VehicleDetector, ModelNotLoadedError


class UnsupportedVideoFormatError(ValueError):
    """Raised when an unsupported video file container or extension is provided."""
    pass


class CorruptedVideoError(IOError):
    """Raised when a video file cannot be opened, is truncated, or has unreadable frames."""
    pass


class EmptyFrameError(ValueError):
    """Raised when an empty or null image frame is passed for processing."""
    pass


@dataclass
class FrameAnalysisResult:
    """
    Comprehensive structured analysis output for a single processed video frame.
    Contains annotations, timestamps, counts, bounding boxes, and traffic engineering metrics.
    """
    frame: np.ndarray                              # Original raw frame
    annotated_frame: np.ndarray                    # Frame overlaid with high-contrast HUD bounding boxes and lanes
    timestamp: float                               # Video timestamp in seconds
    frame_index: int                               # Sequential frame index
    detections: List[Detection]                    # Detected vehicle entities with track IDs and bounding boxes
    detection_counts: Dict[str, int]               # Instantaneous count per vehicle class {'car': x, 'bus': y, ...}
    unique_vehicles_count: int                     # Cumulative unique vehicles tracked across the video so far
    unique_counts_by_class: Dict[str, int]         # Cumulative unique vehicles broken down by vehicle class
    active_vehicles_count: int                     # Instantaneous number of vehicles visible in this frame
    estimated_flow_rate_vph: float                 # Estimated traffic throughput rate in Vehicles Per Hour (veh/h)
    lane_counts: Dict[str, int]                    # Breakdown of vehicles by approach lane (North, South, East, West)
    pcu_total: float                               # Total Passenger Car Units (PCU) present in this frame
    is_synthetic: bool = False                     # True if generated by procedural synthetic simulation
    backend_name: str = "Unknown"                  # Detection engine backend utilized
    processing_time_ms: float = 0.0                # Frame inference and annotation duration in milliseconds


class SyntheticVehicle:
    """Simulates a vehicle entity with kinematic properties on an intersection."""
    def __init__(
        self,
        vehicle_id: int,
        lane: str,
        vehicle_type: str,
        pos: float,
        speed: float,
        color: Tuple[int, int, int],
    ):
        self.vehicle_id = vehicle_id        # Persistent track identifier
        self.lane = lane                    # 'North', 'South', 'East', 'West'
        self.vehicle_type = vehicle_type    # 'car', 'bus', 'truck', 'motorcycle'
        self.pos = pos                      # Distance along the approach lane (0.0 to 1.0)
        self.speed = speed                  # Movement step per frame
        self.color = color                  # BGR color
        self.stopped = False

        # Physical dimensions based on vehicle type
        if vehicle_type == "car":
            self.width, self.length = 24, 40
            self.pcu = 1.0
        elif vehicle_type == "bus":
            self.width, self.length = 28, 70
            self.pcu = 3.0
        elif vehicle_type == "truck":
            self.width, self.length = 28, 65
            self.pcu = 3.0
        else:  # motorcycle
            self.width, self.length = 14, 24
            self.pcu = 0.5


class SyntheticTrafficStream:
    """
    Procedural 4-way intersection traffic simulator.
    Renders high-definition synthetic frames complete with road markings,
    crosswalks, traffic lights, and animated vehicles respecting signal states.
    Allows zero-dependency live demonstration of the computer vision pipeline.
    """
    def __init__(self, width: int = 720, height: int = 540):
        self.width = width
        self.height = height
        self.vehicles: List[SyntheticVehicle] = []
        self.frame_count = 0
        self.active_phase = "North-South"  # "North-South" or "East-West"
        self.phase_timer = 0
        self.phase_duration = 120  # frames per phase
        self._init_population()

    def _init_population(self):
        """Initializes a fleet of vehicles with persistent IDs across all four approaches."""
        configs = [
            (1, "North", "car", 0.15, 0.006, (230, 180, 40)),
            (2, "North", "motorcycle", 0.35, 0.008, (80, 220, 120)),
            (3, "North", "bus", 0.60, 0.004, (30, 150, 240)),
            (4, "South", "car", 0.10, 0.007, (220, 120, 40)),
            (5, "South", "truck", 0.40, 0.005, (60, 60, 220)),
            (6, "South", "car", 0.70, 0.006, (200, 200, 200)),
            (7, "East", "car", 0.20, 0.006, (40, 200, 220)),
            (8, "East", "car", 0.50, 0.007, (240, 100, 150)),
            (9, "West", "bus", 0.25, 0.004, (30, 150, 240)),
            (10, "West", "motorcycle", 0.55, 0.009, (80, 220, 120)),
            (11, "West", "car", 0.75, 0.006, (220, 220, 80)),
        ]
        self.vehicles = [
            SyntheticVehicle(vid, lane=lane, vehicle_type=vtype, pos=pos, speed=spd, color=col)
            for vid, lane, vtype, pos, spd, col in configs
        ]

    def set_signal_phase(self, phase: str) -> None:
        """Manually or dynamically controls the active green phase."""
        if phase in ["North-South", "East-West"]:
            self.active_phase = phase

    def step(self) -> None:
        """Updates physics and signals for the next frame."""
        self.frame_count += 1
        self.phase_timer += 1

        # Automatically toggle signal if not overridden externally
        if self.phase_timer >= self.phase_duration:
            self.active_phase = "East-West" if self.active_phase == "North-South" else "North-South"
            self.phase_timer = 0

        # Update vehicle positions
        for v in self.vehicles:
            is_green = (
                (v.lane in ["North", "South"] and self.active_phase == "North-South")
                or (v.lane in ["East", "West"] and self.active_phase == "East-West")
            )

            # Stop line is approximately at pos = 0.45
            # If red light and approaching stop line, decelerate/stop
            if not is_green and 0.38 <= v.pos <= 0.46:
                v.stopped = True
            else:
                v.stopped = False
                v.pos += v.speed

            # Reset vehicle loop when it passes the intersection
            if v.pos > 1.05:
                v.pos = -0.05

    def render_frame(self) -> np.ndarray:
        """Renders the graphical top-down intersection view."""
        w, h = self.width, self.height
        # Dark asphalt background
        frame = np.full((h, w, 3), (25, 30, 40), dtype=np.uint8)

        road_w = min(w, h) // 4
        cx, cy = w // 2, h // 2

        # Draw road corridors
        cv2.rectangle(frame, (cx - road_w // 2, 0), (cx + road_w // 2, h), (45, 52, 65), -1)
        cv2.rectangle(frame, (0, cy - road_w // 2), (w, cy + road_w // 2), (45, 52, 65), -1)

        # Draw curb borders
        curb_color = (75, 85, 100)
        cv2.line(frame, (cx - road_w // 2, 0), (cx - road_w // 2, cy - road_w // 2), curb_color, 2)
        cv2.line(frame, (cx + road_w // 2, 0), (cx + road_w // 2, cy - road_w // 2), curb_color, 2)
        cv2.line(frame, (cx - road_w // 2, cy + road_w // 2), (cx - road_w // 2, h), curb_color, 2)
        cv2.line(frame, (cx + road_w // 2, cy + road_w // 2), (cx + road_w // 2, h), curb_color, 2)

        cv2.line(frame, (0, cy - road_w // 2), (cx - road_w // 2, cy - road_w // 2), curb_color, 2)
        cv2.line(frame, (0, cy + road_w // 2), (cx - road_w // 2, cy + road_w // 2), curb_color, 2)
        cv2.line(frame, (cx + road_w // 2, cy - road_w // 2), (w, cy - road_w // 2), curb_color, 2)
        cv2.line(frame, (cx + road_w // 2, cy + road_w // 2), (w, cy + road_w // 2), curb_color, 2)

        # Yellow dashed centerlines
        dash_color = (40, 200, 230)
        for y in range(0, cy - road_w // 2, 24):
            cv2.line(frame, (cx, y), (cx, y + 14), dash_color, 2)
        for y in range(cy + road_w // 2, h, 24):
            cv2.line(frame, (cx, y), (cx, y + 14), dash_color, 2)
        for x in range(0, cx - road_w // 2, 24):
            cv2.line(frame, (x, cy), (x + 14, cy), dash_color, 2)
        for x in range(cx + road_w // 2, w, 24):
            cv2.line(frame, (x, cy), (x + 14, cy), dash_color, 2)

        # White stop lines
        stop_color = (220, 220, 225)
        cv2.line(frame, (cx - road_w // 2, cy - road_w // 2), (cx, cy - road_w // 2), stop_color, 3)
        cv2.line(frame, (cx, cy + road_w // 2), (cx + road_w // 2, cy + road_w // 2), stop_color, 3)
        cv2.line(frame, (cx - road_w // 2, cy), (cx - road_w // 2, cy + road_w // 2), stop_color, 3)
        cv2.line(frame, (cx + road_w // 2, cy - road_w // 2), (cx + road_w // 2, cy), stop_color, 3)

        # Crosswalk stripes
        for k in range(-road_w // 2 + 8, road_w // 2 - 8, 14):
            cv2.rectangle(frame, (cx + k, cy - road_w // 2 - 16), (cx + k + 8, cy - road_w // 2 - 4), (160, 160, 165), -1)
            cv2.rectangle(frame, (cx + k, cy + road_w // 2 + 4), (cx + k + 8, cy + road_w // 2 + 16), (160, 160, 165), -1)

        # Render vehicles
        for v in self.vehicles:
            vx, vy = self._get_vehicle_coords(v, cx, cy, road_w, h, w)
            if 0 <= vx < w and 0 <= vy < h:
                bw, bl = v.width, v.length
                if v.lane in ["North", "South"]:
                    cv2.rectangle(frame, (vx - bw // 2, vy - bl // 2), (vx + bw // 2, vy + bl // 2), v.color, -1)
                    cv2.rectangle(frame, (vx - bw // 2, vy - bl // 2), (vx + bw // 2, vy + bl // 2), (255, 255, 255), 1)
                    hl_y = vy + bl // 2 if v.lane == "North" else vy - bl // 2
                    cv2.circle(frame, (vx - bw // 3, hl_y), 2, (255, 255, 200), -1)
                    cv2.circle(frame, (vx + bw // 3, hl_y), 2, (255, 255, 200), -1)
                else:
                    cv2.rectangle(frame, (vx - bl // 2, vy - bw // 2), (vx + bl // 2, vy + bw // 2), v.color, -1)
                    cv2.rectangle(frame, (vx - bl // 2, vy - bw // 2), (vx + bl // 2, vy + bw // 2), (255, 255, 255), 1)
                    hl_x = vx + bl // 2 if v.lane == "West" else vx - bl // 2
                    cv2.circle(frame, (hl_x, vy - bw // 3), 2, (255, 255, 200), -1)
                    cv2.circle(frame, (hl_x, vy + bw // 3), 2, (255, 255, 200), -1)

        # Traffic Signal Heads on 4 corners
        self._render_signals(frame, cx, cy, road_w)

        # Watermark / Simulation Banner
        cv2.putText(
            frame,
            "SYNTHETIC BENCHMARK STREAM [SIMULATION ENGINE ACTIVE]",
            (14, 24),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.45,
            (238, 211, 34),
            1,
            cv2.LINE_AA,
        )

        return frame

    def _render_signals(self, frame: np.ndarray, cx: int, cy: int, road_w: int):
        """Draws functional signal status lights on corner posts."""
        ns_green = self.active_phase == "North-South"
        ew_green = not ns_green

        ns_color = (60, 220, 60) if ns_green else (40, 40, 230)
        ew_color = (60, 220, 60) if ew_green else (40, 40, 230)

        cv2.circle(frame, (cx + road_w // 2 + 15, cy - road_w // 2 - 15), 8, ns_color, -1)
        cv2.circle(frame, (cx - road_w // 2 - 15, cy + road_w // 2 + 15), 8, ns_color, -1)
        cv2.putText(frame, "NS", (cx + road_w // 2 + 28, cy - road_w // 2 - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (255, 255, 255), 1)

        cv2.circle(frame, (cx - road_w // 2 - 15, cy - road_w // 2 - 15), 8, ew_color, -1)
        cv2.circle(frame, (cx + road_w // 2 + 15, cy + road_w // 2 + 15), 8, ew_color, -1)
        cv2.putText(frame, "EW", (cx - road_w // 2 - 45, cy - road_w // 2 - 10), cv2.FONT_HERSHEY_SIMPLEX, 0.4, (255, 255, 255), 1)

    def _get_vehicle_coords(self, v: SyntheticVehicle, cx: int, cy: int, road_w: int, h: int, w: int) -> Tuple[int, int]:
        """Calculates pixel coordinates from relative road position."""
        lane_offset = road_w // 4
        if v.lane == "North":
            vx = cx - lane_offset
            vy = int(v.pos * h)
        elif v.lane == "South":
            vx = cx + lane_offset
            vy = int((1.0 - v.pos) * h)
        elif v.lane == "West":
            vx = int(v.pos * w)
            vy = cy + lane_offset
        else:  # East
            vx = int((1.0 - v.pos) * w)
            vy = cy - lane_offset
        return vx, vy

    def get_detections(self, frame: np.ndarray) -> List[Detection]:
        """Returns ground-truth detections with persistent track IDs for synthetic frame."""
        cx, cy = self.width // 2, self.height // 2
        road_w = min(self.width, self.height) // 4
        detections: List[Detection] = []

        for v in self.vehicles:
            vx, vy = self._get_vehicle_coords(v, cx, cy, road_w, self.height, self.width)
            if 10 <= vx <= self.width - 10 and 10 <= vy <= self.height - 10:
                bw = v.width if v.lane in ["North", "South"] else v.length
                bh = v.length if v.lane in ["North", "South"] else v.width
                x1 = max(0, vx - bw // 2)
                y1 = max(0, vy - bh // 2)
                x2 = min(self.width, vx + bw // 2)
                y2 = min(self.height, vy + bh // 2)

                detections.append(
                    Detection(
                        bbox=(x1, y1, x2, y2),
                        class_name=v.vehicle_type,
                        confidence=0.96,
                        center=(vx, vy),
                        track_id=v.vehicle_id,  # Ground-truth persistent track ID
                        lane_id=v.lane,
                        pcu_weight=v.pcu,
                    )
                )
        return detections


class VideoProcessor:
    """
    Unified Video Stream and File Processor.
    Handles video ingestion, camera capture, frame sampling, batch processing,
    and synthetic benchmark generation.
    """
    SUPPORTED_EXTENSIONS = {".mp4", ".avi", ".mov", ".mkv", ".webm", ".flv", ".wmv", ".m4v"}

    def __init__(
        self,
        detector: Optional[VehicleDetector] = None,
        frame_sampling_interval: int = 1,
    ):
        self.detector = detector if detector is not None else VehicleDetector()
        self.frame_sampling_interval = max(1, frame_sampling_interval)
        self.cap: Optional[cv2.VideoCapture] = None
        self.synthetic_stream = SyntheticTrafficStream()
        self.video_path: Optional[str] = None
        self.fps: float = 30.0
        self.total_frames: int = 0
        self.current_frame_idx: int = 0

    def open_video_file(self, file_path: str) -> bool:
        """
        Validates and opens a local video file.
        Raises UnsupportedVideoFormatError if file format is unsupported.
        Raises CorruptedVideoError if video file is missing, empty, or unreadable by OpenCV.
        """
        if not os.path.exists(file_path):
            raise FileNotFoundError(f"Video file not found at path: '{file_path}'")

        _, ext = os.path.splitext(file_path.lower())
        if ext not in self.SUPPORTED_EXTENSIONS:
            raise UnsupportedVideoFormatError(
                f"Unsupported video file extension '{ext}'. "
                f"Supported formats: {', '.join(sorted(self.SUPPORTED_EXTENSIONS))}"
            )

        if os.path.getsize(file_path) == 0:
            raise CorruptedVideoError(f"Video file '{file_path}' is empty (0 bytes).")

        self.close()
        self.cap = cv2.VideoCapture(file_path)

        if not self.cap.isOpened():
            raise CorruptedVideoError(
                f"Failed to open video file '{file_path}'. File may be corrupted, truncated, or lacks codec support."
            )

        # Test first frame decode to ensure file is not corrupted
        ret, test_frame = self.cap.read()
        if not ret or test_frame is None or test_frame.size == 0:
            self.close()
            raise CorruptedVideoError(
                f"Video file '{file_path}' could not be decoded. Frames are unreadable or missing video track."
            )

        # Reset pointer back to first frame
        self.cap.set(cv2.CAP_PROP_POS_FRAMES, 0)
        self.video_path = file_path
        self.fps = max(1.0, float(self.cap.get(cv2.CAP_PROP_FPS) or 30.0))
        self.total_frames = int(self.cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)
        self.current_frame_idx = 0
        return True

    def open_camera(self, camera_index: int = 0) -> bool:
        """Opens local hardware camera device index."""
        self.close()
        self.cap = cv2.VideoCapture(camera_index)
        if not self.cap.isOpened():
            return False
        self.fps = 30.0
        self.total_frames = 0
        self.current_frame_idx = 0
        self.video_path = f"camera://{camera_index}"
        return True

    def close(self) -> None:
        """Releases open capture handles and resets stream pointer."""
        if self.cap is not None:
            self.cap.release()
            self.cap = None
        self.video_path = None
        self.current_frame_idx = 0

    def get_video_info(self) -> Dict[str, Any]:
        """Retrieves properties of the active video feed or synthetic engine."""
        if self.cap and self.cap.isOpened():
            return {
                "width": int(self.cap.get(cv2.CAP_PROP_FRAME_WIDTH)),
                "height": int(self.cap.get(cv2.CAP_PROP_FRAME_HEIGHT)),
                "fps": max(1.0, float(self.cap.get(cv2.CAP_PROP_FPS) or 30.0)),
                "frame_count": int(self.cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0),
                "is_synthetic": False,
                "video_path": self.video_path,
                "sampling_interval": self.frame_sampling_interval,
            }
        return {
            "width": self.synthetic_stream.width,
            "height": self.synthetic_stream.height,
            "fps": 30.0,
            "frame_count": 1000,
            "is_synthetic": True,
            "video_path": "synthetic://benchmark_stream",
            "sampling_interval": self.frame_sampling_interval,
        }

    def read_frame(self) -> Optional[np.ndarray]:
        """Reads the next raw frame from open video file or camera."""
        if self.cap and self.cap.isOpened():
            ret, frame = self.cap.read()
            if ret and frame is not None and frame.size > 0:
                self.current_frame_idx += 1
                return frame
        return None

    def read_synthetic_frame(self) -> Tuple[np.ndarray, List[Detection]]:
        """Advances simulation and returns rendered synthetic frame with ground-truth detections."""
        self.synthetic_stream.step()
        frame = self.synthetic_stream.render_frame()
        detections = self.synthetic_stream.get_detections(frame)
        self.current_frame_idx += 1
        return frame, detections

    def process_frame(
        self,
        frame: Optional[np.ndarray],
        timestamp: Optional[float] = None,
        frame_index: Optional[int] = None,
        is_synthetic: bool = False,
    ) -> FrameAnalysisResult:
        """
        Executes complete video frame processing pipeline:
        Detection -> Multi-Object Tracking -> Metric Aggregation -> HUD Rendering.
        Handles empty or corrupted frames gracefully.
        """
        t0 = time.time()
        idx = frame_index if frame_index is not None else self.current_frame_idx
        ts = timestamp if timestamp is not None else (idx / self.fps if self.fps > 0 else 0.0)

        # Graceful handling for empty or invalid frames
        if frame is None or not isinstance(frame, np.ndarray) or frame.size == 0 or len(frame.shape) < 2:
            empty_annotated = np.zeros((540, 720, 3), dtype=np.uint8)
            return FrameAnalysisResult(
                frame=np.zeros((540, 720, 3), dtype=np.uint8),
                annotated_frame=empty_annotated,
                timestamp=ts,
                frame_index=idx,
                detections=[],
                detection_counts={"car": 0, "bus": 0, "truck": 0, "motorcycle": 0, "total": 0},
                unique_vehicles_count=self.detector.tracker.get_unique_vehicle_count(),
                unique_counts_by_class=self.detector.tracker.get_unique_counts_by_class(),
                active_vehicles_count=0,
                estimated_flow_rate_vph=0.0,
                lane_counts={"North": 0, "South": 0, "East": 0, "West": 0},
                pcu_total=0.0,
                is_synthetic=is_synthetic,
                backend_name=self.detector.backend,
                processing_time_ms=0.0,
            )

        # Run vehicle detection and tracking
        if is_synthetic:
            detections = self.detector.detect(frame, synthetic_stream=self.synthetic_stream, timestamp=ts)
        else:
            detections = self.detector.detect(frame, timestamp=ts)

        # Compute instant detection counts
        counts: Dict[str, int] = {"car": 0, "bus": 0, "truck": 0, "motorcycle": 0}
        lane_counts: Dict[str, int] = {"North": 0, "South": 0, "East": 0, "West": 0}
        pcu_total = 0.0

        for d in detections:
            cname = d.class_name.lower()
            if cname in counts:
                counts[cname] += 1
            else:
                counts["car"] += 1

            lane = d.lane_id if d.lane_id in lane_counts else "North"
            lane_counts[lane] += 1
            pcu_total += d.pcu_weight

        counts["total"] = len(detections)

        # Retrieve tracker metrics
        unique_total = self.detector.tracker.get_unique_vehicle_count()
        unique_by_class = self.detector.tracker.get_unique_counts_by_class()
        flow_rate = self.detector.tracker.compute_traffic_flow_rate(elapsed_seconds=ts)

        # Draw annotations
        status_banner = (
            f"Active: {len(detections)} veh | Unique Tracks: {unique_total} | "
            f"Flow: {int(flow_rate)} veh/h | Backend: {self.detector.backend}"
        )
        annotated = self.detector.draw_detections(
            frame,
            detections,
            draw_lanes=True,
            show_labels=True,
            show_tracks=True,
            show_trails=True,
            tracker=self.detector.tracker,
            header_text=status_banner,
        )

        dt_ms = round((time.time() - t0) * 1000.0, 2)

        return FrameAnalysisResult(
            frame=frame,
            annotated_frame=annotated,
            timestamp=round(ts, 3),
            frame_index=idx,
            detections=detections,
            detection_counts=counts,
            unique_vehicles_count=unique_total,
            unique_counts_by_class=unique_by_class,
            active_vehicles_count=len(detections),
            estimated_flow_rate_vph=flow_rate,
            lane_counts=lane_counts,
            pcu_total=round(pcu_total, 1),
            is_synthetic=is_synthetic,
            backend_name=self.detector.backend,
            processing_time_ms=dt_ms,
        )

    def process_batch(
        self,
        frames: List[np.ndarray],
        start_index: int = 0,
        fps: float = 30.0,
    ) -> List[FrameAnalysisResult]:
        """
        Processes a batch of consecutive frames sequentially.
        Enables efficient CPU utilization while maintaining persistent multi-object tracking.
        """
        results: List[FrameAnalysisResult] = []
        for i, frame in enumerate(frames):
            idx = start_index + i
            ts = idx / fps if fps > 0 else 0.0
            res = self.process_frame(frame, timestamp=ts, frame_index=idx)
            results.append(res)
        return results

    def process_video(
        self,
        file_path: Optional[str] = None,
        frame_interval: Optional[int] = None,
        max_frames: Optional[int] = None,
        batch_size: int = 1,
    ) -> Generator[FrameAnalysisResult, None, None]:
        """
        Streaming generator that reads video frames at a configurable frame-sampling interval.
        Yields FrameAnalysisResult items one by one.
        
        Args:
            file_path: Optional path to open; uses active capture if None.
            frame_interval: Sampling interval (e.g. 3 = process every 3rd frame).
            max_frames: Maximum number of processed frames to yield before stopping.
            batch_size: Number of frames per batch iteration.
        """
        if file_path is not None:
            self.open_video_file(file_path)

        if self.cap is None or not self.cap.isOpened():
            raise CorruptedVideoError("No active video feed opened for processing.")

        interval = frame_interval if frame_interval is not None else self.frame_sampling_interval
        interval = max(1, interval)

        frames_processed = 0
        raw_frame_idx = 0

        while True:
            ret, frame = self.cap.read()
            if not ret or frame is None:
                break

            # Frame sampling check
            if raw_frame_idx % interval == 0:
                ts = raw_frame_idx / self.fps if self.fps > 0 else 0.0
                result = self.process_frame(frame, timestamp=ts, frame_index=raw_frame_idx)
                yield result
                frames_processed += 1

                if max_frames is not None and frames_processed >= max_frames:
                    break

            raw_frame_idx += 1

    @staticmethod
    def check_tripwire_crossing(
        center: Tuple[int, int],
        tripwire_p1: Tuple[int, int],
        tripwire_p2: Tuple[int, int],
        track_id: Optional[int],
        crossed_set: Set[int],
        tolerance: int = 14,
    ) -> bool:
        """
        Evaluates whether a vehicle has intersected the virtual counting line.
        Prevents repeated counting of the same vehicle entity using persistent track IDs.
        """
        if track_id is None:
            return False

        if track_id in crossed_set:
            return True

        cx, cy = center
        x1, y1 = tripwire_p1
        x2, y2 = tripwire_p2

        # Horizontal or near-horizontal tripwire
        if abs(x2 - x1) >= abs(y2 - y1):
            min_x, max_x = min(x1, x2), max(x1, x2)
            target_y = (y1 + y2) // 2
            if min_x - 20 <= cx <= max_x + 20 and abs(cy - target_y) <= tolerance:
                crossed_set.add(track_id)
                return True
        else:  # Vertical tripwire
            min_y, max_y = min(y1, y2), max(y1, y2)
            target_x = (x1 + x2) // 2
            if min_y - 20 <= cy <= max_y + 20 and abs(cx - target_x) <= tolerance:
                crossed_set.add(track_id)
                return True

        return False

    @staticmethod
    def is_inside_roi(center: Tuple[int, int], roi: Optional[Tuple[int, int, int, int]]) -> bool:
        """Checks whether vehicle centroid falls inside the region of interest."""
        if roi is None:
            return True
        cx, cy = center
        x1, y1, x2, y2 = roi
        return x1 <= cx <= x2 and y1 <= cy <= y2

    @staticmethod
    def get_video_metadata(file_path: str) -> Optional[Dict[str, Any]]:
        """Extracts resolution, duration, FPS, and total frame count from a video file."""
        if not file_path or not os.path.exists(file_path):
            return None

        cap = cv2.VideoCapture(file_path)
        if not cap.isOpened():
            return None

        width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        fps = float(cap.get(cv2.CAP_PROP_FPS) or 30.0)
        total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0)
        duration_sec = total_frames / fps if fps > 0 else 0.0

        mins = int(duration_sec // 60)
        secs = int(duration_sec % 60)
        duration_str = f"{mins:02d}:{secs:02d}"

        try:
            size_mb = round(os.path.getsize(file_path) / (1024 * 1024), 2)
        except Exception:
            size_mb = 0.0

        cap.release()
        return {
            "width": width,
            "height": height,
            "fps": round(fps, 1),
            "total_frames": total_frames,
            "duration_seconds": round(duration_sec, 2),
            "duration_formatted": duration_str,
            "file_size_mb": size_mb,
        }
